-- Run once against an empty PostgreSQL database before starting the application.
BEGIN;

CREATE TABLE user_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    steam_id VARCHAR(20) NOT NULL,
    persona_name VARCHAR(255) NOT NULL,
    avatar_full TEXT,
    loc_country_code VARCHAR(2),
    current_mmr INTEGER CHECK (current_mmr >= 0),
    mmr_stars INTEGER CHECK (mmr_stars BETWEEN 1 AND 6),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_user_profile_steam_id UNIQUE (steam_id)
);

CREATE TABLE match_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id VARCHAR(128) NOT NULL,
    steam_id VARCHAR(20) NOT NULL,
    match_time TIMESTAMPTZ NOT NULL,
    map_name VARCHAR(100) NOT NULL,
    game_mode VARCHAR(50) NOT NULL,
    extracted BOOLEAN NOT NULL DEFAULT FALSE,
    kills INTEGER NOT NULL DEFAULT 0 CHECK (kills >= 0),
    team_kills INTEGER NOT NULL DEFAULT 0 CHECK (team_kills >= 0),
    deaths INTEGER NOT NULL DEFAULT 0 CHECK (deaths >= 0),
    assists INTEGER NOT NULL DEFAULT 0 CHECK (assists >= 0),
    team_wipes INTEGER NOT NULL DEFAULT 0 CHECK (team_wipes >= 0),
    bounty_extracted INTEGER NOT NULL DEFAULT 0 CHECK (bounty_extracted >= 0),
    mmr INTEGER CHECK (mmr >= 0),
    mmr_change INTEGER,
    encountered_players JSONB NOT NULL DEFAULT '[]'::jsonb,
    CONSTRAINT uk_match_record_match_id UNIQUE (match_id),
    CONSTRAINT fk_match_record_user_profile FOREIGN KEY (steam_id)
        REFERENCES user_profile (steam_id),
    CONSTRAINT ck_match_record_encountered_players_array
        CHECK (jsonb_typeof(encountered_players) = 'array')
);

CREATE INDEX idx_match_record_steam_time
    ON match_record (steam_id, match_time DESC, id DESC);

COMMIT;
